-- Preserve the old preview's order for existing keys, then record insertion
-- order independently of timestamps. Rapid rotations can share one timestamp.
ALTER TABLE user_signing_keys ADD COLUMN insertion_id BIGINT;

WITH previous_keys AS (
  SELECT user_id, fp,
    ROW_NUMBER() OVER (ORDER BY created_at ASC NULLS LAST, fp ASC, user_id ASC) AS n
  FROM user_signing_keys
)
UPDATE user_signing_keys AS keys SET insertion_id = previous_keys.n
FROM previous_keys WHERE keys.user_id = previous_keys.user_id AND keys.fp = previous_keys.fp;

ALTER TABLE user_signing_keys ALTER COLUMN insertion_id SET NOT NULL;
ALTER TABLE user_signing_keys ALTER COLUMN insertion_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('user_signing_keys', 'insertion_id'),
  COALESCE((SELECT MAX(insertion_id) FROM user_signing_keys), 0) + 1, false);
CREATE INDEX idx_user_signing_keys_insertion ON user_signing_keys (user_id, insertion_id DESC);
